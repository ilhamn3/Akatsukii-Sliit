def main():
    parser = argparse.ArgumentParser(
        description="Factory Memory: Multi-Agent Industrial Repair Knowledge System"
    )
    parser.add_argument(
        "--mode",
        choices=["cli", "ui"],
        default="cli",
        help="Execution mode: 'cli' runs graph; 'ui' launches Streamlit app",
    )
    parser.add_argument(
        "--query",
        type=str,
        default="Spindle high-pitched whining noise at 3000 RPM; chuck pressure dropping below 15 bar.",
        help="Industrial troubleshooting query or symptom description",
    )
    parser.add_argument(
        "--machine-type",
        type=str,
        default=None,
        help="Optional industrial machine classification (defaults to unspecified if omitted)",
    )
    parser.add_argument(
        "--machine-id",
        type=str,
        default=None,
        help="Optional machine serial or asset identifier",
    )
    parser.add_argument(
        "--fake-llm",
        action="store_true",
        help="Run offline using deterministic FakeLLM simulation",
    )

    args = parser.parse_args()

    if args.fake_llm:
        os.environ["FACTORY_FAKE_LLM"] = "1"

    if args.mode == "ui":
        ui_path = Path(__file__).resolve().parent / "ui" / "app.py"
        if ui_path.exists():
            subprocess.run(["streamlit", "run", str(ui_path)], check=True)
        else:
            print(
                f"[INFO] Streamlit UI module not found at '{ui_path}'.\n"
                "UI implementation is owned by Kajanan K. (WP6) and is pending merge.\n"
                "Run CLI assistance via:\n"
                "    python project/main.py --mode cli --query \"<symptom description>\""
            )
        return

    # CLI Execution Mode
    is_stub = is_pipeline_stub("B")
    is_fake_llm = os.getenv("FACTORY_FAKE_LLM") == "1"
    machine_display = args.machine_type if args.machine_type else "unspecified"

    print("=" * 80)
    print(" 🏭 FACTORY MEMORY — Multi-Agent Knowledge Transfer System")
    print("=" * 80)
    print(f"[*] Query:        {args.query}")
    print(f"[*] Machine:      {machine_display}")
    if args.machine_id:
        print(f"[*] Asset ID:     {args.machine_id}")

    try:
        final_state = run_assistance_workflow(
            query=args.query,
            machine_type=args.machine_type,
            machine_id=args.machine_id,
        )

        # 1. Workflow halted on clarifying question
        if final_state.get("clarification_needed"):
            q = final_state.get("clarification_question") or "Additional clarification required."
            if is_fake_llm:
                print("\n*** FAKE LLM - CANNED OUTPUT - NOT REAL DIAGNOSIS ***")
            print("\n--- [CLARIFICATION REQUIRED] ---")
            print(f"  • Question: {q}")
            print(f"\n[*] Trace ID:       {final_state.get('trace_id', 'TR-UNKNOWN')}")
            print(f"[*] Audit Log:      {DEFAULT_LOG_PATH.resolve()}")
            if is_fake_llm:
                print("*** FAKE LLM - CANNED OUTPUT - NOT REAL DIAGNOSIS ***")
            return

        # 2. Workflow completed with final answer
        final_ans_dict = final_state.get("final_answer")
        final_answer = None
        if final_ans_dict:
            try:
                final_answer = FinalAnswer.model_validate(final_ans_dict)
            except Exception:
                pass

        if not final_answer:
            final_answer = FinalAnswer(
                machine_type=machine_display,
                symptoms=[args.query],
                diagnosed_cause="Workflow concluded without explicit diagnosis",
                steps=[],
                abstained=True,
                abstention_reason="No conclusive guidance generated by assistance pipeline.",
                trace_id=final_state.get("trace_id", "TR-UNKNOWN"),
            )

        if is_fake_llm:
            print("\n*** FAKE LLM - CANNED OUTPUT - NOT REAL DIAGNOSIS ***")
        if is_stub:
            print("*** UPSTREAM STUB: evidence comes from the placeholder retrieval stub; steps are grounded in that stub data only ***")
            print("--- [DUMMY WORKFLOW RESULT] ---")
        else:
            print("\n--- [WORKFLOW EXECUTION RESULT] ---")

        print(f"  • Diagnosed Cause: {final_answer.diagnosed_cause}")
        print(f"  • Abstained:       {final_answer.abstained}")
        if final_answer.abstained:
            print(f"  • Reason:          {final_answer.abstention_reason}")
        if final_answer.escalated:
            print(f"  • Escalated:       True (supervisor review required)")
        print(f"  • Safety notes:    {len(final_answer.safety_warnings)} (rule/advisory)")
        for w in final_answer.safety_warnings:
            print(f"    - {w}")

        if final_answer.failed_attempts_to_avoid:
            print(f"  • Failed Attempts to Avoid: {len(final_answer.failed_attempts_to_avoid)}")
            for fa in final_answer.failed_attempts_to_avoid:
                print(f"    - DO NOT REPEAT: {fa}")

        evidence_map = {
            e.get("evidence_id"): e.get("content", "")
            for e in final_state.get("evidence", [])
            if e.get("evidence_id")
        }

        print(f"  • Action Steps:    {len(final_answer.steps)} cited steps")
        for step in final_answer.steps:
            cits = ", ".join(step.evidence_ids) if step.evidence_ids else "None"
            print(f"    {step.step_number}. {step.instruction} [Citations: {cits}]")
            for eid in step.evidence_ids:
                if eid in evidence_map:
                    print(f"       ↳ [Grounded in {eid}]: \"{evidence_map[eid]}\"")

        print(f"\n[*] Trace ID:       {final_answer.trace_id}")
        print(f"[*] Audit Log:      {DEFAULT_LOG_PATH.resolve()}")

        if is_stub:
            print("*** UPSTREAM STUB: evidence comes from the placeholder retrieval stub; steps are grounded in that stub data only ***")
        if is_fake_llm:
            print("*** FAKE LLM - CANNED OUTPUT - NOT REAL DIAGNOSIS ***")

    except Exception as e:
        print(f"\n[ERROR] Pipeline execution failed: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
