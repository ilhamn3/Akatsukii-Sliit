def run_assistance_workflow(
    query: str,
    machine_type: Optional[str] = None,
    machine_id: Optional[str] = None,
    worker_id: str = "worker-default",
) -> BlackboardState:
    """Execute Pipeline B multi-agent assistance graph and return the final BlackboardState."""
    initial_state = create_initial_state(
        query=query,
        machine_type=machine_type,
        machine_id=machine_id,
        worker_id=worker_id,
    )

    graph = build_graph(pipeline="B")
    return graph.invoke(initial_state)


def run_assistance(
    query: str,
    machine_type: Optional[str] = None,
    machine_id: Optional[str] = None,
    worker_id: str = "worker-default",
) -> FinalAnswer:
    """Execute Pipeline B multi-agent assistance workflow and return the final answer.

    Args:
        query: Worker symptom query or troubleshooting question.
        machine_type: Optional machine category (defaults to 'unspecified').
        machine_id: Optional specific asset tag.
        worker_id: Operator badge or user identifier.

    Returns:
        Structured FinalAnswer containing cited repair steps, safety checks, or abstention.
    """
    final_state = run_assistance_workflow(
        query=query,
        machine_type=machine_type,
        machine_id=machine_id,
        worker_id=worker_id,
    )

    effective_machine = machine_type or "unspecified"

    # Check if workflow paused on clarification
    if final_state.get("clarification_needed"):
        q = final_state.get("clarification_question") or "Additional clarification required."
        return FinalAnswer(
            machine_type=effective_machine,
            symptoms=[query],
            diagnosed_cause=f"Clarification Required: {q}",
            steps=[],
            abstained=True,
            abstention_reason=f"CLARIFICATION NEEDED: {q}",
            trace_id=final_state.get("trace_id", "TR-UNKNOWN"),
        )

    final_ans_dict = final_state.get("final_answer")
    if final_ans_dict:
        try:
            return FinalAnswer.model_validate(final_ans_dict)
        except Exception:
            pass

    # Construct safe fallback / abstention FinalAnswer if none produced
    return FinalAnswer(
        machine_type=effective_machine,
        symptoms=[query],
        diagnosed_cause="Workflow concluded without explicit diagnosis",
        steps=[],
        abstained=True,
        abstention_reason="No conclusive guidance generated by assistance pipeline.",
        trace_id=final_state.get("trace_id", "TR-UNKNOWN"),
    )


