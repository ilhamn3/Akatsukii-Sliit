"""Pydantic v2 core schemas for Factory Memory.

Defines the shared data contracts across all 8 agents in Pipeline A (Ingestion)
and Pipeline B (Assistance), including repair episodes, inter-agent messaging,
diagnostic hypotheses, retrieved evidence, safety verdicts, and final answers.
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field, model_validator


class RepairStep(BaseModel):
    """An individual step within a documented repair procedure."""

    step_number: int = Field(ge=1, description="1-indexed sequence number of the repair step")
    description: str = Field(..., min_length=3, description="Detailed instruction for this step")
    timestamp: Optional[str] = Field(
        default=None,
        description="Source audio/video timestamp offset (e.g., '02:15' or '00:01:45')"
    )
    evidence_id: Optional[str] = Field(
        default=None,
        description="Granular evidence ID associated with this step (e.g., 'EV-CNC-0014-S2')"
    )


class FailedAttempt(BaseModel):
    """A documented past repair attempt that was ineffective or hazardous."""

    action: str = Field(..., min_length=3, description="Action attempted by the technician")
    outcome: str = Field(..., min_length=3, description="Observed consequence or result")
    why_failed: str = Field(..., min_length=3, description="Root mechanical or procedural reason for failure")


class RepairRecord(BaseModel):
    """Full structured repair episode captured in Pipeline A and stored in the knowledge base."""

    machine_type: str = Field(..., min_length=2, description="Target machine classification")
    machine_id: Optional[str] = Field(default=None, description="Specific asset or serial identifier")
    symptoms: List[str] = Field(..., min_length=1, description="List of observed symptoms or alarms")
    steps: List[RepairStep] = Field(..., min_length=1, description="Sequential repair steps with timestamps")
    tools: List[str] = Field(default_factory=list, description="Tools and equipment required")
    parts: List[str] = Field(default_factory=list, description="Replacement components and part numbers")
    root_cause: str = Field(..., min_length=3, description="Verified underlying fault or failure mode")
    failed_attempts: List[FailedAttempt] = Field(
        default_factory=list,
        description="Historical actions that failed to resolve the issue"
    )
    safety_warnings: List[str] = Field(
        default_factory=list,
        description="Critical safety warnings, LOTO requirements, or hazard notices"
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Ingestion extraction confidence score (threshold for HITL is 0.75)"
    )
    evidence_id: str = Field(..., min_length=3, description="Primary unique evidence identifier")
    source: str = Field(..., min_length=2, description="Origin modality (e.g., audio_debrief, shift_log, manual)")


class AgentMessage(BaseModel):
    """Standard message payload exchanged between agents or logged to audit traces."""

    sender: str = Field(..., min_length=1, description="Identifier of the emitting agent")
    receiver: str = Field(..., min_length=1, description="Identifier of the target agent or 'blackboard'")
    type: str = Field(..., min_length=1, description="Message type (e.g., 'DIAGNOSTIC_QUERY', 'VETO')")
    payload: Dict[str, Any] = Field(default_factory=dict, description="Structured message body")
    trace_id: str = Field(..., min_length=1, description="Correlation identifier for the execution trace")
    ts: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="UTC timestamp in ISO 8601 format"
    )


class Hypothesis(BaseModel):
    """A ranked fault hypothesis generated by the Diagnostic Agent."""

    rank: int = Field(ge=1, description="Rank priority (1 = most probable)")
    fault: str = Field(..., min_length=3, description="Hypothesized root cause or failure mechanism")
    subsystem: str = Field(..., min_length=2, description="Affected subsystem or component assembly")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Estimated diagnostic probability")
    rationale: Optional[str] = Field(default=None, description="Diagnostic reasoning justifying this hypothesis")


class Evidence(BaseModel):
    """A grounded piece of historical repair evidence retrieved from the knowledge store."""

    evidence_id: str = Field(..., min_length=1, description="Unique evidence ID (e.g., 'EV-CNC-0014-S2')")
    episode_id: str = Field(..., min_length=1, description="Parent repair episode ID")
    source_type: str = Field(..., description="Store origin: 'sqlite', 'vector', or 'graph'")
    content: str = Field(..., min_length=1, description="Textual description of the verified repair or step")
    similarity_score: float = Field(default=0.0, ge=0.0, le=1.0, description="Retrieval similarity score")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Additional context or attributes")


class SafetyVerdict(BaseModel):
    """Verdict emitted by the Safety Verification Agent after evaluating candidate repair steps."""

    verdict: Literal["approve", "amend", "veto"] = Field(
        ...,
        description="'approve' = plan is safe; 'amend' = minor edits needed; 'veto' = dangerous shortcut/violation"
    )
    reason: str = Field(..., min_length=1, description="Safety evaluation justification")
    rule_ids: List[str] = Field(
        default_factory=list,
        description="IDs of deterministic safety rules evaluated or triggered"
    )
    suggested_amendments: Optional[List[str]] = Field(
        default=None,
        description="Mandatory procedural additions (e.g., 'Insert LOTO step at PB-02')"
    )


class ActionStep(BaseModel):
    """A recommended actionable step presented to the junior worker with grounded citations."""

    step_number: int = Field(ge=1, description="1-indexed execution order")
    instruction: str = Field(..., min_length=3, description="Specific repair action to carry out")
    evidence_ids: List[str] = Field(
        default_factory=list,
        description="Evidence IDs grounding this instruction (e.g., ['EV-CNC-0014-S1'])"
    )


class FinalAnswer(BaseModel):
    """Final synthesized guidance generated by the Orchestrator for the junior technician."""

    machine_type: str = Field(..., min_length=2, description="Target machine classification")
    symptoms: List[str] = Field(..., min_length=1, description="Observed symptoms addressed")
    diagnosed_cause: str = Field(..., min_length=2, description="Selected root-cause diagnosis")
    steps: List[ActionStep] = Field(default_factory=list, description="Cited step-by-step repair instructions")
    safety_warnings: List[str] = Field(
        default_factory=list,
        description="Enforced safety prerequisites (LOTO, pressure bleed, PPE)"
    )
    failed_attempts_to_avoid: List[str] = Field(
        default_factory=list,
        description="Historical mistakes that must not be repeated"
    )
    abstained: bool = False
    escalated: bool = False
    abstention_reason: Optional[str] = None
    trace_id: str = Field(..., min_length=1, description="Trace ID linking this answer to the audit log")

    @model_validator(mode="after")
    def validate_steps_if_not_abstained(self) -> "FinalAnswer":
        # If not abstained and not escalated, steps must not be empty
        if not self.abstained and not self.escalated and len(self.steps) == 0:
            raise ValueError("Action steps cannot be empty unless abstained or escalated.")
        return self
